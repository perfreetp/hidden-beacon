import { DEFAULT_PARAMS } from '../src/model/params.js';
import { buildArrayModel } from '../src/model/geometry.js';
import { initManifold, buildDag, DagEvaluator } from '../src/model/manifoldDag.js';
const params = { ...DEFAULT_PARAMS, span: 24000, panelLength: 1000, cols: 12, rows: 4, circularSegments: 16 };
const t0 = performance.now();
const model = buildArrayModel(params);
console.log('gen ms', (performance.now()-t0).toFixed(0), JSON.stringify(model.stats));
await initManifold();
const dag = buildDag(model);
const ev = new DagEvaluator(dag, 16);
ev.setPrimitives(model);
const t1 = performance.now();
const man = ev.evaluateAll();
console.log('boolean total ms', (performance.now()-t1).toFixed(0), 'tri', man.numTri(), 'status', man.status());
console.log('timings', JSON.stringify(ev.timings), 'booleans', ev.booleans);
const target = model.members.find(m=>m.type==='chord');
const rec = model.primitives.find(r=>r.memberId===target.memberId);
rec.length*=1.2; const h=rec.length/2;
rec.p1=rec.center.map((c,i)=>c-rec.dir[i]*h); rec.p2=rec.center.map((c,i)=>c+rec.dir[i]*h);
const t2=performance.now();
ev.reevaluateAfterEdit([rec.id]);
console.log('incremental ms', (performance.now()-t2).toFixed(1));
